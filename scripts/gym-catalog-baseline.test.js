"use strict";
const {ok,finish}=require("./ok");
const fs=require("fs"),path=require("path");
const root=path.join(__dirname,"..");
const load=(file,name)=>{const m=new module.constructor();m._compile(fs.readFileSync(path.join(root,file),"utf8")+`;module.exports=${name}`,file);return m.exports};
const EXDB=require("../www/modules/gym/exlib.js");
const generated=EXDB.slice();
const BAL=require("../www/modules/gym/balance.js");
const runtime=EXDB.slice();
const T=load("www/modules/gym/figtpl.js","FigTpl");
const C=load("www/modules/gym/excues.js","EXCUE");
const WALK=runtime.slice(generated.length).filter(e=>e.id==="fastwalk"||e.id==="slowwalk");
const all=runtime,ids=all.map(e=>e.id);
const required=["id","n","r","g","k","q","l","c","tp"];
ok("generated catalog baseline is exactly 324 records",generated.length===324);
ok("balance supplemental baseline is six records",BAL.length===6);
ok("walking supplemental baseline is two records",WALK.length===2&&WALK.every(e=>e.id==="fastwalk"||e.id==="slowwalk"));
ok("full runtime baseline has 332 unique records",all.length===332&&new Set(ids).size===all.length,all.length);
ok("every catalog record has required fields",all.every(e=>required.every(k=>typeof e[k]==="string"&&e[k].length>0)),all.filter(e=>!required.every(k=>typeof e[k]==="string"&&e[k].length>0)).map(e=>e.id));
ok("every catalog record has a known figure and form cue",all.every(e=>T[e.tp]&&Array.isArray(C[e.tp])&&C[e.tp].length>0),all.filter(e=>!T[e.tp]||!C[e.tp]).map(e=>e.id));
ok("catalog ids and names are unique",new Set(ids).size===ids.length&&new Set(all.map(e=>e.n)).size===all.length);
ok("catalog enums stay within production values",all.every(e=>["w","b","t","i","c"].includes(e.k)&&["g","e","p","k","d"].includes(e.c)&&["Başlangıç","Orta","İleri"].includes(e.l)));
finish();
