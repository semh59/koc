/* A delivered dose notification is cleared only when its own day's dose (every dose of its minute) is marked. */
const {ok,finish}=require("./ok");
const {boot}=require("./html");
const unclock=require("./clock").at;

(async()=>{
  const gone=[];let delivered=[];
  const w=await boot(w=>{w.Capacitor={isNativePlatform:()=>true,Plugins:{LocalNotifications:{checkPermissions:async()=>({display:"granted"}),requestPermissions:async()=>({display:"granted"}),checkExactNotificationSetting:async()=>({exact_alarm:"granted"}),getPending:async()=>({notifications:[]}),getDeliveredNotifications:async()=>({notifications:delivered}),removeDeliveredNotifications:async o=>{gone.push(...o.notifications.map(n=>n.id))},registerActionTypes:async()=>{},cancel:async()=>{},schedule:async()=>{}}}}});
  const ev=s=>w.eval(s),restore=unclock(w,8);
  const run=async(meds,marks,id)=>{
    gone.length=0;delivered=[{id}];
    ev(`S=structuredClone(DEF);S.settings.obDone=true;S.settings.noticeOk=true;S.settings.medOn=true;S.meds=MedLib.cleanMeds(${JSON.stringify(meds)});S.medLog=[];`);
    for(const [mid,off] of marks)ev(`MedLib.mark(S,${mid},calOff(${off}),'08:00','t','08:00')`);
    await ev("scheduleReminders()");
    return gone.includes(id);
  };
  const A={id:1,n:"A",t:["08:00"],on:true,s:"2026-01-01"},B={id:2,n:"B",t:["08:00"],on:true,s:"2026-01-01"};
  ok("yesterday's 08:00 dose taken, today's not: today's 08:00 notification stays",!(await run([A],[[1,-1]],1001000)));
  ok("today's dose taken: its notification is cleared",await run([A],[[1,0]],1001000));
  ok("two doses in the same minute: one taken, the group notification stays",!(await run([A,B],[[1,0]],1001000)));
  ok("two doses in the same minute: both taken, it is cleared",await run([A,B],[[1,0],[2,0]],1001000));
  restore();
  /* yesterday's unmarked 22:00 dose tapped on Today is stamped with the real time, so the double-dose check sees it */
  const restore7=unclock(w,7);
  ev(`S=structuredClone(DEF);S.settings.obDone=true;S.settings.noticeOk=true;S.settings.medOn=true;S.meds=MedLib.cleanMeds([{id:1,n:'A',t:['22:00','08:00'],on:true,s:'2026-01-01'}]);S.medLog=[];tab='today';render()`);
  ev("window.__confirmAuto=m=>{globalThis.__asked=(globalThis.__asked||0)+1;return false}");
  ev("medMark(1,'22:00','t',false,calOff(-1))");
  ok("yesterday's dose marked on Today gets the time of the tap",/^\d\d:\d\d$/.test(ev("S.medLog[0].at||''")),ev("JSON.stringify(S.medLog)"));
  ev("medMark(1,'08:00','t',false,calKey())");
  ok("the next dose right after it asks before saving",ev("globalThis.__asked")===1&&ev("S.medLog.length")===1,ev("globalThis.__asked"));
  restore7();
  /* a dose whose time has just come is "Saati geldi"; "Gecikti" and the near-contact button only after 30 minutes */
  const restore8=unclock(w,8);
  ev(`S=structuredClone(DEF);S.settings.obDone=true;S.settings.noticeOk=true;S.settings.medOn=true;S.settings.medNear='Ali';S.meds=MedLib.cleanMeds([{id:1,n:'A',t:['08:00'],on:true,s:'2026-01-01'}]);S.medLog=[];tab='today';render()`);
  const todo=()=>w.document.querySelector(".todo").textContent;
  ok("dose time just reached: 'Saati geldi', no 'Gecikti', no near-contact button",/Saati geldi/.test(todo())&&!/Gecikti/.test(todo())&&!w.document.querySelector('[data-md="nearsend"]'),todo());
  ev("S.meds=MedLib.cleanMeds([{id:1,n:'A',t:['07:00'],on:true,s:'2026-01-01'}]);render()");
  ok("an hour late: 'Gecikti' with the near-contact button",/Gecikti/.test(todo())&&!!w.document.querySelector('[data-md="nearsend"]'),todo());
  ev("S.meds=MedLib.cleanMeds([{id:1,n:'A',t:['08:00'],on:true,s:'2026-01-01'},{id:2,n:'B',t:['08:00'],on:true,s:'2026-01-01'},{id:3,n:'C',t:['13:00'],on:true,s:'2026-01-01'}]);S.medLog=[];render()");
  ok("two doses of the same minute: one 'Hepsini aldım' button, none for a single dose",w.document.querySelectorAll('[data-md="takeall:08:00"]').length===1&&!w.document.querySelector('[data-md^="takeall:13"]'));
  w.document.querySelector('[data-md="takeall:08:00"]').click();
  ok("it marks both doses taken with one tap",ev("S.medLog.filter(x=>x.day===calKey()&&x.st==='t').length")===2);
  ev("undoLast()");
  ok("one undo takes both back",ev("S.medLog.filter(x=>x.day===calKey()).length")===0);
  ev("S.meds=MedLib.cleanMeds([{id:1,n:'A',t:['08:20'],on:true,s:'2026-01-01'}]);S.medLog=[];render()");
  ok("a dose 20 minutes ahead is the one 'Sıradaki' line to the Meds screen, not a row with buttons",/Sıradaki: 08:20 A/.test(todo())&&!w.document.querySelector('[data-md="take:1:08:20"]')&&!!w.document.querySelector('.todo button.prow[data-tab="meds"]'),todo());
  ev("S.meds=MedLib.cleanMeds([{id:1,n:'A',t:['08:00'],on:true,s:'2026-01-01'},{id:2,n:'B',t:['08:00'],on:true,s:'2026-01-01'}]);S.medLog=[];render()");
  ok("'Hepsini aldım' is a row of its own, apart from the dose buttons",(r=>r&&!r.querySelector('[data-md^="take:"]'))(w.document.querySelector('[data-md="takeall:08:00"]').closest(".row")));
  ev("S.meds=MedLib.cleanMeds([{id:1,n:'A',t:['06:00','07:00'],on:true,s:'2026-01-01'}]);S.medLog=[];MedLib.mark(S,1,calKey(),'06:00','t','06:00');MedLib.mark(S,1,calKey(),'07:00','t','07:00');tab='trend';render();tab='today';render()");
  const yl=()=>w.document.querySelector(`.todo [data-md="dday:${ev("calOff(-1)")}"]`);
  ok("two unmarked doses of yesterday are one line, no buttons per dose",!!yl()&&/Dün 2 doz işaretlenmedi/.test(todo())&&!w.document.querySelector('.todo [data-md^="take:"]'),todo());
  ok("the line still puts the card above the rings and keeps the double-dose sentence",!!w.document.querySelector(".bgtop .todo")&&/ikiye katlama/.test(todo()));
  yl().click();
  ok("the line opens yesterday on the Meds screen",ev("tab")==="meds"&&ev("medViewDay()")===ev("calOff(-1)"));
  ev("goBack()");
  ok("and back returns to Today",ev("tab")==="today");
  w.document.querySelector('.todo [data-md="dtoday"]').click();
  ok("the next-dose line then opens today, not the yesterday seen before",ev("tab")==="meds"&&ev("medViewDay()")===ev("calKey()"));
  ev("tab='today';S.settings.dayStart=9;render()");
  ok("before the day start yesterday's doses stay late rows with buttons",!yl()&&w.document.querySelectorAll('.todo [data-md^="take:"]').length===2&&/Gecikti/.test(todo()));
  ev("S.settings.dayStart=0");
  ev("S.meds=MedLib.cleanMeds([{id:1,n:'A',t:['09:00'],on:true,s:'2026-01-01'}]);render()");
  ok("a dose an hour ahead is not listed yet",!w.document.querySelector('[data-md="take:1:09:00"]'));
  ev("S.meds=MedLib.cleanMeds([{id:1,n:'A',t:['07:00'],on:true,s:'2026-01-01'}]);S.medLog=[];render()");
  ev("MedLib.mark(S,1,calKey(),'07:00','s');render()");
  ok("a skipped dose is counted as skipped, not as done",/0\/1 alındı, 1 atlandı/.test(todo().replace(/\s+/g," "))||/0\/1 alındı, 1 atlandı/.test(w.document.querySelector(".todo .hint").textContent),w.document.querySelector(".todo")?.textContent);
  ev("S.meds=MedLib.cleanMeds([{id:1,n:'A',t:['08:00'],on:true,s:'2026-01-01'}]);S.medLog=[{id:1,m:1,day:calKey(),slot:'08:00',st:'t'},{m:1,day:calOff(-1),slot:'08:00',st:'t'}];tab='today';render();todoSig=''");
  ev("S.medLog=[];todoTick()");
  ok("the minute tick redraws Today when a dose row appears",!!w.document.querySelector('[data-md="take:1:08:00"]'));
  ev("S=structuredClone(DEF);S.settings.obDone=true;S.settings.noticeOk=true;S.entries=[{id:1,day:dayKey(),time:'01:00',type:'water',v:250,text:''}];S.nextId=2;tab='today';logOff=0;render()");
  const offer=()=>!!w.document.querySelector('[data-act="lateok"]');
  ok("the night-entries offer is shown for an entry before 04:00",offer());
  w.document.querySelector('[data-act="lateok"]').click();
  ok("'Bugüne ait' hides the offer",!offer());
  ev("undoLast()");
  ok("and its undo brings the offer back",offer());
  ev("tab='day';logOff=0;render()");
  ok("today's Day screen offers it too; a past day does not",offer()&&(ev("logOff=1;render()"),!offer()));
  ev("S=structuredClone(DEF);S.settings.obDone=true;S.settings.noticeOk=true;S.settings.dayStart=2;S.entries=[{id:1,day:dayKey(),time:'02:30',type:'water',v:250,text:''}];S.nextId=2;tab='today';logOff=0;render()");
  ok("with a day start of 02:00 an entry at 02:30 is offered for yesterday",offer());
  ev("S.entries=[{id:1,day:dayKey(),time:'05:00',type:'water',v:250,text:''}];render()");
  ok("an entry at 05:00 is not offered",!offer());
  ev("S=structuredClone(DEF);S.settings.obDone=true;S.settings.noticeOk=true;S.entries=[1,2,3].map(i=>({id:i,day:dayKey(),time:'0'+(4+i)+':00',type:'food',v:100,text:'Yemek '+i}));S.nextId=4;tab='day';logOff=0;render()");
  for(let i=0;i<3;i++)w.document.querySelector(".log .del").click();
  ok("three deletions remove three entries",ev("S.entries.length")===0);
  for(let i=0;i<3;i++)ev("undoLast()");
  ok("three undos bring all three back, in order",ev("S.entries.map(e=>e.id).sort().join()")==="1,2,3",ev("S.entries.length"));
  restore8();
  finish();
})();
