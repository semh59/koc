"use strict";
const fs=require("fs"),path=require("path"),vm=require("vm");
const root=path.join(__dirname,".."),batchDir=path.join(__dirname,"gym-catalog/batches");
const {CANONICAL_FIELDS}=require("./gym-catalog-semantic");
const {SOURCES}=require("./gym-provenance");
const legacySources=new Map(fs.readFileSync(path.join(__dirname,"exlib-src.txt"),"utf8").split(/\r?\n/).filter(l=>l&&!l.startsWith("#")).map(l=>{const p=l.split("|");return [p[1],p[0]]}));
const localIds=["onefoot","heeltoe","chairstand","sidestep","tandem","armswalk","fastwalk","slowwalk"];
const templates=require("../www/modules/gym/figtpl");
const context={};vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root,"www/modules/gym/excues.js"),"utf8")+";this.cues=EXCUE",context);
const readBatches=()=>fs.readdirSync(batchDir).filter(f=>f.endsWith(".json")).sort().map(f=>JSON.parse(fs.readFileSync(path.join(batchDir,f),"utf8")));
function compile(batches){
  const ids=new Set(),records=[],external=[],local=[];
  for(const b of batches){
    if(b.schemaVersion!==1||Object.keys(b).some(k=>!["schemaVersion","batch","records"].includes(k))||!Array.isArray(b.records)||!b.records.length)throw Error("invalid batch schema");
    for(const item of b.records){
      if(!item||typeof item!=="object"||Array.isArray(item)||Object.keys(item).some(k=>!["runtime","metadata"].includes(k)))throw Error("unknown record field");
      const {runtime:e,metadata:m}=item;
      if(!e||!m||!e.id||ids.has(e.id))throw Error("missing or duplicate id");
      ids.add(e.id);
      if(Object.keys(e).some(k=>!["id","n","r","g","k","q","l","c","inc","tp","im","pr","o"].includes(k))||Object.keys(m).some(k=>!["canonical_id","canonical","signature","family","cue_ids","figure_template","source_ref","license_ref","source_name","retrieved_at","transformation_note","status"].includes(k)))throw Error(`unknown record field: ${e.id}`);
      if((e.pr!==undefined&&!["-","bar","bar@sh","db","db@sh","kb","ball"].includes(e.pr))||(e.o!==undefined&&(!e.o||typeof e.o!=="object"||Array.isArray(e.o)||!Object.entries(e.o).every(([k,v])=>require("../www/modules/gym/figlib").KEYS.includes(k)&&Number.isFinite(v)&&Math.abs(v)<=360))))throw Error(`invalid figure override: ${e.id}`);
      if(!["id","n","r","g","k","q","l","c","tp"].every(k=>typeof e[k]==="string"&&e[k].trim()))throw Error(`missing runtime field: ${e.id}`);
      if(!["w","b","t","i","c"].includes(e.k)||!["g","e","k","p","d"].includes(e.c)||!["Ağırlıksız","Ev tipi","Salon"].includes(e.q)||!["Başlangıç","Orta","İleri"].includes(e.l)||!Number.isFinite(e.inc)||e.inc<=0)throw Error(`invalid runtime value: ${e.id}`);
      if(!(Object.hasOwn(templates,e.tp)&&Array.isArray(templates[e.tp].frames)&&Object.hasOwn(context.cues,e.tp)&&Array.isArray(context.cues[e.tp])&&context.cues[e.tp].length>0&&context.cues[e.tp].every(c=>typeof c==="string"&&c.trim()))||m.figure_template!==e.tp||JSON.stringify(m.cue_ids)!==JSON.stringify([e.tp]))throw Error(`figure or cue missing: ${e.id}`);
      if(!SOURCES[m.source_ref]||m.license_ref!==m.source_ref||!["verified","internal"].includes(SOURCES[m.source_ref].licenseStatus))throw Error(`source or license missing: ${e.id}`);
      if(!["legacy-external","legacy-local"].includes(b.batch))throw Error("new batches blocked until B-4 visual pilot and admission gate");
      if(!m.source_name||!m.transformation_note||m.retrieved_at!==null||m.status!=="review"||m.canonical_id!==null||m.signature!==null||m.family!==null||!m.canonical||Object.keys(m.canonical).length!==CANONICAL_FIELDS.length||!CANONICAL_FIELDS.every(k=>m.canonical[k]===null))throw Error(`legacy metadata must remain explicit review: ${e.id}`);
      if(b.batch==="legacy-external"){
        if(legacySources.get(e.id)!==m.source_name)throw Error(`legacy source mapping changed: ${e.id}`);
        if(m.source_ref!=="free-exercise-db-data"||![0,1,2].includes(e.im))throw Error(`external source mismatch: ${e.id}`);
        external.push(e);
      }else{
        if(!localIds.includes(e.id))throw Error(`legacy source mapping changed: ${e.id}`);
        if(m.source_ref!=="neowell-data"||e.im!=null)throw Error(`local source mismatch: ${e.id}`);
        local.push(e);
      }
      records.push({id:e.id,...m});
    }
  }
  if(external.length!==324||local.length!==8)throw Error("legacy source inventory changed");
  const exlib='"use strict";\n/* Generated by scripts/build-gym-catalog.js from scripts/gym-catalog/batches. Do not edit by hand. */\nconst EXDB='+JSON.stringify(external)+';\nif(typeof module!=="undefined")module.exports=EXDB;\n';
  const balance=local.filter(e=>e.c==="d"),walk=local.filter(e=>e.c==="k");
  if(balance.length!==6||walk.length!==2)throw Error("legacy supplemental inventory changed");
  const supplement='"use strict";\n/* Generated by scripts/build-gym-catalog.js; general movement practice, not treatment. */\nconst EXBAL='+JSON.stringify(balance)+';\nconst EXWALK='+JSON.stringify(walk)+';\n(typeof EXDB!=="undefined"?EXDB:require("./exlib.js")).push(...EXBAL,...EXWALK);\nif(typeof module!=="undefined")module.exports=EXBAL;\n';
  const ordered=[...external,...local];
  const byId=new Map(records.map(e=>[e.id,e]));
  return {"www/modules/gym/exlib.js":exlib,"www/modules/gym/balance.js":supplement,"docs/analysis/gym-catalog-metadata.json":JSON.stringify({schemaVersion:1,sourceCount:external.length,localCount:local.length,runtimeCount:ordered.length,acceptedNewRecords:0,semanticUniqueCount:0,reviewCount:records.length,records:ordered.map(e=>byId.get(e.id))},null,2)+"\n"};
}
if(require.main===module){
  try{
    const check=process.argv.includes("--check"),unknown=process.argv.slice(2).filter(x=>x!=="--check");
    if(unknown.length)throw Error("usage: node scripts/build-gym-catalog.js [--check]");
    const outputs=compile(readBatches());
    for(const [file,text] of Object.entries(outputs)){
      const target=path.join(root,file);
      if(check){if(!fs.existsSync(target)||fs.readFileSync(target,"utf8").replace(/\r\n/g,"\n")!==text)throw Error(`generated output differs: ${file}`)}
      else fs.writeFileSync(target,text);
    }
    console.log(`Catalog ${check?"verified":"generated"}: 324 external + 8 local = 332 runtime; 0 new; 332 review; no network or image writes`);
  }catch(e){console.error(e.message);process.exitCode=1}
}
module.exports={compile,readBatches};
