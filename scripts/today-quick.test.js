/* Today quick chips, first-run nudges and the notes moved behind the info button. */
const {ok,finish}=require("./ok");
const {boot}=require("./html");
(async()=>{
  const w=await boot(),ev=s=>w.eval(s),q=s=>w.document.querySelector(s),all=s=>[...w.document.querySelectorAll(s)];
  const fresh=(extra="")=>ev(`S=structuredClone(DEF);S.settings.obDone=true;S.settings.noticeOk=true;${extra};tab='today';render()`);
  const chips=()=>all(".qa .chip").map(c=>c.dataset.chip);
  fresh();
  ok("chips without modules: water, drink, weight, exercise, note, walk in that order",chips().join()==="water,drink,weight,exercise,note,walk",chips());
  ok("the drink chip is named İçecek türü",q('[data-chip="drink"]').textContent.includes("İçecek türü")&&!q(".qa").textContent.includes("Başka içecek"));
  fresh("S.settings.bpOn=true;S.settings.bsOn=true");
  ok("blood pressure and glucose chips open their sheets when the modules are on",chips().includes("bp")&&chips().includes("bs")&&q('[data-chip="bp"]').dataset.vt==="addbp"&&q('[data-chip="bs"]').dataset.vt==="addbs");
  q('[data-chip="bp"]').click();
  ev("closeSheet()");
  ok("chips keep a fixed order: water and drink first, then Kilo, Spor, the module chips, Not, Yürüyüş",chips().join()==="water,drink,weight,exercise,bp,bs,note,walk",chips());
  q('[data-chip="note"]').click();ev("closeSheet()");
  ok("using a chip never moves it",chips().join()==="water,drink,weight,exercise,bp,bs,note,walk"&&ev("'chipUse' in S.settings")===false);
  ok("the drink chip sits in one group with the water chip",q('.qpair [data-chip="water"]')&&q('.qpair [data-chip="drink"]'));
  fresh("S.settings.glass=150");
  ok("the water chip label follows the glass size",q('[data-chip="water"]').textContent.includes("+150 ml"));
  ev("tab='coach';render()");
  ok("the Coach composer water chip follows the glass size",q("#cglass").textContent==="+150");
  fresh("add('food',300,'Çorba');for(let i=1;i<=4;i++)add('note',null,'Not '+i)");
  ok("Today opens the first 3 entries; the rest, day copy and template fold into one 'Daha fazla'",all("#view .log").length===1&&all(".log>li.row").length===3&&q(".log>li>details>summary").textContent==="Daha fazla (2 kayıt)"&&all(".log details .row").length===2&&!!q('.log details [data-act="cp:day"]')&&!!q('.log details [data-act="tplnew"]')&&all('#view [data-act="cp:day"]').length===1);
  ev("tab='day';logOff=0;render()");
  ok("the Day screen lists every entry, nothing folded",all(".log .row").length===5&&!q(".log details"));
  fresh("S.settings.obNudge=true");
  ok("after setup, a first-water row adds one glass in one tap",q(".todo")&&q('.todo [data-act="water"]'));
  q('.todo [data-act="water"]').click();
  ok("the first-water row disappears once water exists",ev("of('water',dayKey()).length")===1&&!q('.todo [data-act="water"]'));
  fresh("S.settings.obSkipped=true");
  ok("after Şimdilik geç, Today offers Hedefini hesapla",q('.todo [data-act="obredo"]'));
  q('.todo [data-act="obredo"]').click();
  ok("it opens the setup form directly, without the welcome page",ev("obNeeded()")&&q("#obcm")&&!q("#view").textContent.includes("hoş geldin"));
  q('[data-ob="skip"]').click();
  ok("skipping again returns to Today and keeps the row",!ev("obNeeded()")&&q('.todo [data-act="obredo"]'));
  fresh("S.settings.age=30;S.settings.kcal=2000;add('weight',80);const f=add('food',300,'Yoğurt');f.p=20;f.fb=5");
  ok("the protein note is behind an info button, closed at first",q('[data-help="hpro"]')&&q("#hpro").hidden);
  ok("the fibre explanation is behind an info button",q('[data-help="hfib"]')&&q("#hfib").hidden);
  ok("the Coach tip is gone from Today",!q(".coachc"));
  ev("tab='trend';render()");
  ok("the Coach tip lives in Trend",!!q(".coachc"));
  /* Setup is short: welcome plus one form, and the first record is one tap on Today. */
  ev("S=structuredClone(DEF);Object.assign(ob,obFresh());tab='today';render()");
  const screens=new Set();const seen=()=>screens.add(ev("obNeeded()")?"ob"+ev("ob.step"):"today");
  seen();q('[data-ob="next"]').click();seen();
  q("#obcm").value="170";q("#obkg").value="70";q("#obage").value="30";
  q('[data-ob="next"]').click();seen();
  ok("the target appears on the same screen after the first Devam",!!q("#obtarget")&&ev("ob.step")===0);
  q('[data-ob="next"]').click();seen();
  ok("setup is welcome plus one form, then Today (no module or summary step)",[...screens].join()==="ob-1,ob0,today",[...screens]);
  ok("the first record is one tap from the setup's end: the water row is on Today",!!q('.todo [data-act="water"]'));
  ok("setup leaves every module off and asks about them the next day, not now",!ev("S.settings.bpOn")&&!q('.todo [data-act="obmods"]'));
  ev("S.settings.obAt=keyOff(-1);render()");
  ok("the next day Today offers the module choice",!!q('.todo [data-act="obmods"]'));
  q('.todo [data-act="obmods"]').click();
  q('[data-om="bp"]').click();q('[data-om="med"]').click();q('[data-om="med"]').click();q('[data-om="save"]').click();
  ok("the chosen modules turn on, the row goes away",ev("S.settings.bpOn")===true&&ev("S.settings.medOn")===false&&ev("S.settings.modAsked")&&!q('.todo [data-act="obmods"]')&&!!q('[data-chip="bp"]'));
  ev("S.settings.modAsked=false;S.settings.obAt=keyOff(-3);render()");
  q('.todo [data-act="obmodsno"]').click();
  ok("Şimdi değil dismisses the module row",!q('.todo [data-act="obmods"]')&&ev("S.settings.modAsked"));
  ev("S.settings.modAsked=false;S.settings.obAt=keyOff(-9);render()");
  ok("the module row is a first-week offer only",!q('.todo [data-act="obmods"]'));
  finish();
})();
