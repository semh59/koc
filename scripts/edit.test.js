/* One edit sheet for log entries (food, water, weight, exercise, note): value, text, day and time; undo; failed save. */
const {ok,finish}=require("./ok");
const {boot,quota}=require("./html");
(async()=>{
  const w=await boot(),ev=s=>w.eval(s),q=s=>w.document.querySelector(s),{full,free}=quota(w);
  ev("S=structuredClone(DEF);S.settings.obDone=true;S.settings.noticeOk=true;tab='today';render()");
  const e=id=>JSON.parse(ev(`JSON.stringify(Log.find(x=>x.id===${id}))`)),open=id=>{ev("render()");if(ev(`Log.find(x=>x.id===${id}).type`)==="water"){ev(`logOff=Algo.dayNum(dayKey())-Algo.dayNum(Log.find(x=>x.id===${id}).day);sheetWater()`);q(`#sheet [data-edit="${id}"]`).click()}else{ev("logOff=0;render()");q(`[data-edit="${id}"]`).click()}};
  const set=(sel,v)=>{q("#sheet "+sel).value=v},save=()=>q('#sheet [data-go="entry"]').click(),err=()=>q("#eerr").textContent;
  const food=ev("add('food',300,'Simit').id"),water=ev("add('water',250).id"),kilo=ev("add('weight',84.3).id"),spor=ev("add('exercise',30,'Koşu').id"),not=ev("add('note',null,'Eski not').id");
  ev("Log.find(x=>x.id===" + spor + ").kcal=200");
  open(food);set("#et","Poğaça");set("#ev","450");set("#etime","09:15");q('#sheet [data-ml="breakfast"]').click();save();
  ok("food: name, kcal, time and meal change; the sheet closes",e(food).text==="Poğaça"&&e(food).v===450&&e(food).time==="09:15"&&e(food).meal==="breakfast"&&!q("#sheet").classList.contains("on"),e(food));
  open(water);set("#ev","500");save();
  ok("water: the amount changes",e(water).v===500);
  open(kilo);set("#ev","83,9");save();
  ok("weight: the value changes",e(kilo).v===83.9);
  open(not);set("#et","Yeni not");save();
  ok("note: the text changes",e(not).text==="Yeni not");
  open(spor);set("#ev","60");save();
  ok("exercise: minutes change and the kcal estimate is recomputed",e(spor).v===60&&e(spor).kcal!==200&&e(spor).kcal>0,e(spor));
  const y=ev("keyOff(-3)");ev("logOff=0");
  open(water);set("#eday",y);save();
  ok("the day can be moved to an earlier day and shows there",e(water).day===y);
  open(water);set("#eday","2999-01-01");save();
  ok("a future day is refused with a message under the field",e(water).day===y&&/gelecek/.test(err())&&q("#sheet").classList.contains("on"),err());
  set("#eday",y);set("#ev","abc");save();
  ok("an invalid value is refused and the entry is unchanged",e(water).v===500&&err()!=="");
  ev("closeSheet()");
  ev("tab='today';render()");
  open(not);set("#et","  ");save();
  ok("an empty note is refused",e(not).text==="Yeni not"&&err()!=="");
  ev("closeSheet()");
  open(food);set("#ev","111");save();
  q("#tundo").click();
  ok("undo brings back the old value",e(food).v===450);
  open(food);set("#ev","222");
  full();
  save();
  ok("a failed save keeps the old record and says so",e(food).v===450&&/kaydedilemedi/.test(q("#tmsg").textContent));
  free();

  /* other record kinds */
  const day=ev("dayKey()"),click=sel=>q(sel).click(),val=(sel,v)=>{q(sel).value=v};
  ev(`S.settings.bpOn=S.settings.bsOn=true;S.vitals=[{id:1,k:"t",day:'${day}',time:"08:00",sys:130,dia:85,pulse:70,session:"morning",sid:"s1",i:1},{id:2,k:"t",day:'${day}',time:"08:00",sys:128,dia:84,session:"morning",sid:"s1",i:2},{id:3,k:"s",day:'${day}',time:"07:00",g:100,ctx:"fasting"}];tab='bp';render()`);
  click('[data-vt^="edit:1"]');val("#bs1","125");val("#bd2","80");val("#vtime","09:10");click('[data-vt="saveedit"]');
  ok("blood pressure session: both readings, time and values are edited together",ev("JSON.stringify(S.vitals.filter(r=>r.k==='t').map(r=>[r.id,r.sys,r.dia,r.time,r.sid]))")==='[[1,125,85,"09:10","s1"],[2,128,80,"09:10","s1"]]');
  click('[data-vt^="edit:1"]');val("#bs1","10");click('[data-vt="saveedit"]');
  ok("an impossible blood pressure is refused under the field",ev("S.vitals[0].sys")===125&&q("#vwarn").textContent!==""&&q("#sheet").classList.contains("on"));
  ev("closeSheet();tab='glucose';render()");
  click('[data-vt="edit:3"]');val("#gv","140");click('[data-vt="vctx"]'.replace('[data-vt="vctx"]','[data-vctx="after"]'));click('[data-vt="saveedit"]');
  ok("glucose: value and context are edited",ev("S.vitals[2].g")===140&&ev("S.vitals[2].ctx")==="after");
  click("#tundo");
  ok("vitals edit can be undone",ev("S.vitals[2].g")===100);
  ev(`S.sleep=[{day:'${y}',min:420,q:3}];S.mood=[{day:'${y}',v:2,t:"yorgun"}];sheetSleepMood()`);
  click(`[data-hb="sedit:${y}"]`);
  ok("sleep: tapping a night opens the sheet filled with its hours, quality and day",q("#hbh").value==="7"&&q("#hbq").value==="3"&&q("#fday").value===y,[q("#hbh").value,q("#hbq").value,q("#fday").value]);
  val("#hbh","8,5");click('[data-hb="sleepgo"]');
  ok("sleep: saving replaces that night",ev("JSON.stringify(S.sleep.map(x=>[x.day,x.min]))")===`[["${y}",510]]`);
  ev("sheetSleepMood()");click(`[data-hb="medit:${y}"]`);
  ok("mood: tapping opens the sheet filled with the note and the day",q("#hbn").value==="yorgun"&&q("#fday").value===y);
  ev("closeSheet()");
  ev(`S.cycle=[{id:1,s:keyOff(-20),e:keyOff(-16),flow:"medium"}];S.settings.cycleOn=true;tab='cycle';render()`);
  click('[data-cy^="edit:"]');
  ok("cycle: the edit sheet comes filled",q("#cys").value===ev("keyOff(-20)")&&q("#cye").value===ev("keyOff(-16)"));
  val("#cye",ev("keyOff(-15)"));val("#cynot","not");click('[data-cy="save"]');
  ok("cycle: the record is replaced, not duplicated",ev("S.cycle.length")===1&&ev("S.cycle[0].e")===ev("keyOff(-15)")&&ev("S.cycle[0].note")==="not");
  ev(`S.measures=[{day:keyOff(-9),k:"waist",v:90}];S.settings.measuresOn=true;msel="waist";tab='more';render()`);
  ev("sheetMeasures(keyOff(-9))");
  ok("measures: the edit sheet shows that day's value and day",q("#fv").value==="90,0"&&q("#fday").value===ev("keyOff(-9)"));
  val("#fv","88,5");val("#fday",ev("keyOff(-2)"));click('[data-ms="go"]');
  ok("measures: the value is replaced and moved to the chosen day",ev("JSON.stringify(S.measures)")===`[{"day":"${ev("keyOff(-2)")}","k":"waist","v":88.5}]`,ev("JSON.stringify(S.measures)"));
  ev(`S.labs=[{id:1,day:keyOff(-5),k:"glukoz",n:"Glukoz",v:90,u:"mg/dL",lo:70,hi:100}];tab='labs';render();labDetail("glukoz|mg/dL")`);
  click('[data-lab="edit:1"]');val("#lev","105");val("#leh","110");click('[data-lab="editgo"]');
  ok("lab result: value and range are edited",ev("S.labs.length")===1&&ev("S.labs[0].v")===105&&ev("S.labs[0].hi")===110&&ev("S.labs[0].lo")===70);
  click("#tundo");
  ok("lab edit can be undone",ev("S.labs[0].v")===90);
  finish();
})();
