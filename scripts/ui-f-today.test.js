/* Audit round 2, section F (Today): folded notes, calorie formula links, caffeine, same-day copy, weekly sport, Enter in the BP sheet, water shortcut, kcal in quick-add toasts. */
const {ok,finish}=require("./ok");
const {boot,until}=require("./html");
(async()=>{
  const w=await boot(),ev=s=>w.eval(s),q=s=>w.document.querySelector(s),all=s=>[...w.document.querySelectorAll(s)];
  const fresh=(extra="")=>ev(`S=structuredClone(DEF);S.settings.obDone=true;S.settings.noticeOk=true;${extra};tab='today';logOff=0;render()`);
  fresh("S.settings.age=30;S.settings.kcal=2000;S.settings.heightCm=170;const f=add('food',300,'Yoğurt');f.p=20;f.fb=5;f.c=10");
  ok("the first screen has one folded Ayrıntı line that holds every note",all(".rings").length===1&&all("details.acc>summary").filter(s=>s.textContent==="Ayrıntı").length===1&&!q("details.acc[open]")&&q("details.acc>summary").closest(".card").querySelector(".macro.num"));
  ok("the notes are inside the fold, not loose in the card",q("details.acc").textContent.includes("Lif")&&q("details.acc").textContent.includes("Bugün az yemek")&&!q(".rings").closest(".card").textContent.replace(q("details.acc").textContent,"").includes("Lif"));
  fresh("add('water',200).dr='coffee';add('water',100).dr='tea'");
  ok("the caffeine total of the day is on Today",/Kafein ~\s*\d+ mg/.test(q(".card .macro")?.textContent||"")&&q(".card .macro").textContent.includes("100"),q(".card .macro")?.textContent);
  fresh("S.settings.heightCm=170;S.settings.age=30");
  ev("tab='settings-profile';render()");
  ok("the calorie field has a Nasıl hesaplandı link, also without a weight record",[...all("details.acc summary")].some(s=>s.textContent==="Nasıl hesaplandı")&&q("#kcal")?.closest(".card").textContent.includes("Mifflin"));
  ev("S=structuredClone(DEF);Object.assign(ob,obFresh());tab='today';render()");
  q('[data-ob="next"]').click();
  q("#obcm").value="170";q("#obkg").value="70";q("#obage").value="30";
  q('[data-ob="next"]').click();
  ok("the onboarding target card explains the formula with the typed numbers",q("#obtarget details.acc")&&q("#obtarget details.acc").textContent.includes("10 × 70,0 kg + 6,25 × 170 cm"),q("#obtarget")?.textContent.slice(0,200));
  fresh();
  ev("S.settings.glass=330;widgetOpen({go:'water'})");
  ok("the launcher Su shortcut opens the drink sheet with Su selected and the glass size ready, and writes nothing",q("#sheet h3").textContent==="İçecek ekle"&&q("#fv").value==="330"&&q("#dr [aria-pressed=true]").dataset.dr==="water"&&ev("S.entries.length")===0);
  ev("closeSheet()");
  fresh("add('food',300,'Çorba').meal='lunch'");
  q('[data-act="yesterday"]');
  ev("sheetCopy('day')");
  q("#fday").value=ev("dayKey()");
  ev("window.confirm=()=>false");
  q('[data-go="cp"]').click();
  await until(()=>false,30);
  ok("copying onto the same day asks first and Vazgeç copies nothing",ev("S.entries.filter(e=>e.type==='food').length")===1);
  ev("window.confirm=()=>true");
  q('[data-go="cp"]').click();
  ok("Yine de kopyala copies once",await until(()=>ev("S.entries.filter(e=>e.type==='food').length")===2));
  ev("closeSheet()");
  fresh("S.entries=[];add('food',250,'Elma')");
  ev("addFoods([{text:'Elma',v:250,meal:'snack'}],dayKey(),'Elma eklendi')");
  ok("a quick add toast names the calories",q("#tmsg").textContent==="Elma eklendi, 250 kcal",q("#tmsg").textContent);
  ev("S.settings.hideNums=true;addFoods([{text:'Elma',v:250,meal:'snack'}],dayKey(),'Elma eklendi')");
  ok("hide-numbers keeps the kcal out of the toast",q("#tmsg").textContent==="Elma eklendi");
  ev("S.settings.hideNums=false");
  fresh("S.settings.bpOn=true");
  ev("sheetBp()");
  q("#bs1").value="120";q("#bd1").value="80";
  q("#bd1").dispatchEvent(new w.KeyboardEvent("keydown",{key:"Enter",bubbles:true}));
  ok("Enter in the blood pressure sheet saves",ev("S.vitals.length")===1);
  fresh("add('water',250).dr='';S.entries=[]");
  ev("S.entries=[];for(let i=0;i<3;i++){const e=add('exercise',30,'Yürüyüş');e.day=keyOff(-i)}for(let i=7;i<9;i++){const e=add('exercise',20,'Yüzme');e.day=keyOff(-i)}add('water',500).day=keyOff(-1);add('water',500).day=keyOff(-8);tab='trend';render()");
  const card=ev("weekCompareCard()");
  ok("the week comparison shows the sport minutes as a weekly total",card.includes("Spor (hafta toplamı, dk)")&&card.includes("90")&&card.includes("40"),card);
  ok("the comparison says which days count",card.includes("tam kayıtlı günlerden"));
  /* The chained undo wakes up after a short pause. */
  fresh();
  q('[data-act="water"]').click();q('[data-act="water"]').click();
  q("#tundo").click();
  ok("the chained Geri al is disabled at once and wakes up after the pause",q("#tundo").disabled&&await until(()=>!q("#tundo").disabled,2000));
  finish();
})();
